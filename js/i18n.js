let lang = "en";
const listeners = new Set();

export const getLang = () => lang;
export const speechLang = () => LANGS[lang].speech;
export const locale = () => LANGS[lang].locale;

/** Troca o idioma; avisa os interessados (onLangChange) só quando muda de fato. */
export function setLang(next) {
  if (!LANGS[next]) next = "en";
  const changed = next !== lang;
  lang = next;
  document.documentElement.lang = LANGS[lang].html;
  if (changed) for (const fn of listeners) fn(lang);
}

export function onLangChange(fn) { listeners.add(fn); }

/** Texto da chave no idioma atual (cai no inglês e, por fim, na própria chave). */
export function t(key, vars = {}) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key];
  if (s === undefined) {
    console.warn(`[i18n] chave sem texto: ${key}`);
    return key;
  }
  if (typeof s === "function") return s(vars);
  if (typeof s !== "string") return s; // listas (ex.: zonas de uma escala)
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

/** Número com o separador decimal do idioma: 27.3 (en) / 27,3 (pt), e sinal de menos tipográfico. */
export function num(v, decimals = 0) {
  const s = Number(v).toFixed(decimals);
  return (lang === "pt" ? s.replace(".", ",") : s).replace(/^-/, "−");
}

/** "a, b and c" / "a, b e c". sep = separador entre os itens. */
export function joinList(list, sep = ", ") {
  const and = lang === "pt" ? " e " : " and ";
  if (list.length <= 1) return list[0] || "";
  if (list.length === 2) return list.join(and);
  // inglês: vírgula antes do "and" (a, b, and c); português: sem vírgula antes do "e"
  const before = sep.trim() === "," && lang === "pt" ? "" : sep.trim();
  return `${list.slice(0, -1).join(sep)}${before}${and}${list[list.length - 1]}`;
}

/** Nome de uma tecla. short = para mostrar num <kbd>; senão, por extenso para a voz. */
export function keyName(key, { short = false } = {}) {
  if (key === " ") return t("key.space");
  if (key === "Arrows") return short ? "← → ↑ ↓" : t("key.arrows");
  if (key === "Escape") return short ? "Esc" : "Escape";
  if (short) return key.length === 1 ? key.toUpperCase() : key;
  const spoken = { "[": "key.openBracket", "]": "key.closeBracket", "+": "key.plus", "-": "key.minus", "=": "key.equals" };
  if (spoken[key]) return t(spoken[key]);
  return key.length === 1 ? key.toUpperCase() : key;
}

/** Aplica os textos à página: data-i18n (conteúdo) e data-i18n-attr ("atributo:chave; ..."). */
export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":").map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  });
}
